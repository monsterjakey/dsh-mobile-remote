#!/usr/bin/env node
/**
 * One-shot deployment setup for dsh-mobile-remote.
 *
 * It reads this machine's tailnet DNS name from `tailscale status --json` and
 * appends two deployment entries to the Desktop profile patch layer:
 *   - connection.trustedHosts  (so the official Host/Origin fence accepts the
 *     tailnet authority; cookie lifetime is shortened to 7 days)
 *   - mobile-remote config     (autoServe + publicBaseUrl)
 *
 * Existing files are backed up; running it twice is a no-op.
 *
 * Usage:
 *   node ~/.dsh/profiles/desktop/node_modules/dsh-mobile-remote/scripts/setup-profile.mjs
 *   # options: DSH_HOME=/path TAILSCALE_BIN=/path/to/tailscale
 */
import { spawnSync } from 'node:child_process'
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'

const MARK_START = '# >>> dsh-mobile-remote setup >>>'
const MARK_END = '# <<< dsh-mobile-remote setup <<<'

const dshHome = process.env.DSH_HOME && process.env.DSH_HOME.length > 0 ? process.env.DSH_HOME : join(homedir(), '.dsh')
const profileName = process.env.DSH_PROFILE && process.env.DSH_PROFILE.length > 0 ? process.env.DSH_PROFILE : 'desktop'
const patchPath = join(dshHome, 'profiles', profileName, 'cordis.patch.yml')
const tailscaleBin = process.env.TAILSCALE_BIN && process.env.TAILSCALE_BIN.length > 0 ? process.env.TAILSCALE_BIN : '/usr/local/bin/tailscale'

function fail(message) {
  console.error(`[setup] ${message}`)
  process.exit(1)
}

if (!existsSync(patchPath)) fail(`profile patch not found: ${patchPath} (open DeepSeek Harness Desktop once first)`)

const status = spawnSync(tailscaleBin, ['status', '--json'], { encoding: 'utf8', timeout: 15000 })
if (status.error !== undefined || status.status !== 0) fail(`cannot run ${tailscaleBin} status --json`)
let dnsName = ''
try {
  dnsName = String(JSON.parse(status.stdout)?.Self?.DNSName ?? '').replace(/\.$/, '')
} catch {
  fail('cannot parse tailscale status JSON')
}
if (dnsName === '') fail('tailnet DNS name is empty; is Tailscale logged in?')

const patch = readFileSync(patchPath, 'utf8')
if (patch.includes(MARK_START)) {
  console.log(`[setup] already configured for ${dnsName}; nothing changed`)
  process.exit(0)
}

const backup = `${patchPath}.bak-mobile-remote-${Date.now()}`
copyFileSync(patchPath, backup)
// A freshly initialized profile patch is the YAML literal `[]`; appending a
// sequence to it would create a second document. Drop that literal first.
let base = patch
if (/^\s*\[\]\s*$/m.test(base)) base = base.replace(/^\s*\[\]\s*$/m, '')
const block = `
${MARK_START}
# generated by dsh-mobile-remote setup-profile.mjs
- id: connection
  name: "@deepseek-ai/dsh-client-connection"
  config:
    trustedHosts: ["${dnsName}"]
    cookieMaxAgeDays: 7
- id: mobile-remote
  name: dsh-mobile-remote
  config:
    autoServe: true
    publicBaseUrl: https://${dnsName}
${MARK_END}
`
writeFileSync(patchPath, `${base.trimEnd()}\n${block}`, 'utf8')

console.log(`[setup] tailnet host: ${dnsName}`)
console.log(`[setup] backup: ${backup}`)
console.log('[setup] patch updated. Restart DeepSeek Harness Desktop, then open:')
console.log(`        https://${dnsName}/__dshm/pair`)
console.log('        pairingCode is in ~/.dsh/mobile-remote.json (0600)')
